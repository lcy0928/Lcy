export const setLang = (l) => { current = DICTS[l] ? l : 'zh'; };
export const getLang = () => current;

export function t(key, vars) {
  let s = DICTS[current][key] ?? DICTS.zh[key] ?? key;
  if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? vars[k] : m));
  return s;
}
